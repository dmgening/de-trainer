const images = { room: room() };
const meta = {};
for (const [name, buf] of Object.entries(images)) {
  const file = `${name}.png`;
  writeFileSync(new URL(`media/${file}`, root), buf);
  meta[name] = {
    file,
    sha256: createHash('sha256').update(buf).digest('hex'),
    mime: 'image/png',
    bytes: buf.length,
    width: buf.readUInt32BE(16),
    height: buf.readUInt32BE(20),
  };
}
writeFileSync(
  new URL('src/media.ts', root),
  `// Generated by scripts/draw.mjs: authored images for the demo and test packages.\nexport const FIXTURE_MEDIA = ${JSON.stringify(meta, null, 2)} as const;\n`,
);
